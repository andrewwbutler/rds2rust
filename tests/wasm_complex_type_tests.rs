    /// The point of parsing environments in LazyMetadata mode, rather than
    /// handing them to the sync parser: a large vector bound in an
    /// environment stays lazy instead of being loaded.
    #[wasm_bindgen_test]
    async fn test_environment_keeps_large_binding_lazy() {
        let items = list_items(parse(ENV_WITH_BIG_VECTOR_STREAM, lazy()).await);
        assert_after(&items, "after");
        assert!(matches!(items[0], RObject::Environment { .. }));
        assert!(
            !items[0].is_fully_loaded(),
            "the 1000-element binding should stay lazy"
        );
        let full_items = list_items(parse(ENV_WITH_BIG_VECTOR_STREAM, full()).await);
        assert!(full_items[0].is_fully_loaded());
    }
