    struct MockRdsInput(Vec<u8>);

    impl AsyncRdsInput for MockRdsInput {
        fn read_at<'a>(&'a self, offset: u64, len: usize) -> AsyncReadFuture<'a> {
            Box::pin(async move {
                let start = (offset as usize).min(self.0.len());
                let end = start.saturating_add(len).min(self.0.len());
                Ok(self.0[start..end].to_vec())
            })
        }

        fn len(&self) -> Option<u64> {
            Some(self.0.len() as u64)
        }
    }

    async fn parse(data: &[u8], config: ParseConfig) -> RObject {
        read_rds_async(
            &MockRdsInput(data.to_vec()),
            config,
            AsyncParseConfig::default(),
        )
        .await
        .expect("parse failed")
        .object
    }

    fn lazy() -> ParseConfig {
        ParseConfig {
            mode: ParseMode::LazyMetadata,
            ..ParseConfig::default()
        }
    }

    fn full() -> ParseConfig {
        ParseConfig {
            mode: ParseMode::Full,
            ..ParseConfig::default()
        }
    }

    fn list_items(obj: RObject) -> Vec<RObject> {
        match obj.into_concrete_deep() {
            RObject::List(items) => items,
            RObject::WithAttributes { object, .. } => list_items(*object),
            other => panic!("expected a list, got {}", other.variant_name()),
        }
    }

    fn assert_after(items: &[RObject], expected: &str) {
        match items.last().map(|item| item.clone().into_concrete()) {
            Some(RObject::Character(values)) => {
                assert_eq!(values.to_strings_with_na("<NA>"), [expected])
            }
            other => panic!("expected trailing {expected:?}, got {other:?}"),
        }
    }

    /// LazyMetadata matches Full mode and reaches the trailing element.
    async fn assert_matches_full(data: &[u8]) {
        let lazy_items = list_items(parse(data, lazy()).await);
        let full_items = list_items(parse(data, full()).await);
        assert_after(&lazy_items, "after");
        assert_eq!(lazy_items, full_items);
    }

