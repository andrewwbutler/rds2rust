    struct MockRdsInput {
        data: Vec<u8>,
    }

    impl AsyncRdsInput for MockRdsInput {
        fn read_at<'a>(&'a self, offset: u64, len: usize) -> AsyncReadFuture<'a> {
            Box::pin(async move {
                let start = offset as usize;
                let end = (start + len).min(self.data.len());
                if start >= self.data.len() {
                    return Ok(Vec::new());
                }
                Ok(self.data[start..end].to_vec())
            })
        }

        fn len(&self) -> Option<u64> {
            Some(self.data.len() as u64)
        }
    }

    /// Parse a stream through the sequential-value path (LazyMetadata mode).
    async fn parse_sequential(data: &[u8]) -> RObject {
        let input = MockRdsInput {
            data: data.to_vec(),
        };
        let config = ParseConfig {
            mode: ParseMode::LazyMetadata,
            ..ParseConfig::default()
        };
        read_rds_async(&input, config, AsyncParseConfig::default())
            .await
            .expect("parse failed")
            .object
    }

    fn unwrap_value(obj: &RObject) -> RObject {
        match obj {
            RObject::WithAttributes { object, .. } => unwrap_value(object),
            RObject::Shared(shared) => {
                let inner = shared.read().expect("shared object lock poisoned");
                unwrap_value(&inner)
            }
            other => other.clone(),
        }
    }

    fn list_items(obj: &RObject) -> Vec<RObject> {
        match unwrap_value(obj) {
            RObject::List(items) => items,
            other => panic!("expected list, got {}", other.variant_name()),
        }
    }

    fn character_values(obj: &RObject) -> Vec<String> {
        match unwrap_value(obj) {
            RObject::Character(values) => values.to_strings_with_na("<NA>"),
            other => panic!("expected character vector, got {}", other.variant_name()),
        }
    }

    fn namespace_values(obj: &RObject) -> Vec<String> {
        match unwrap_value(obj) {
            RObject::Namespace(names) => names.iter().map(|s| s.to_string()).collect(),
            other => panic!("expected namespace, got {}", other.variant_name()),
        }
    }

    fn package_values(obj: &RObject) -> Vec<String> {
        match unwrap_value(obj) {
            RObject::PackageEnv(names) => names.iter().map(|s| s.to_string()).collect(),
            other => panic!("expected package env, got {}", other.variant_name()),
        }
    }

    #[wasm_bindgen_test]
    async fn test_persistsxp_payload_consumed_sequential() {
        let obj = parse_sequential(PERSISTSXP_STREAM).await;
        let items = list_items(&obj);
        assert_eq!(items.len(), 3);
        assert_eq!(character_values(&items[0]), ["env::1"]);
        assert_eq!(character_values(&items[1]), ["env::1"]);
        // The critical assertion: the element after the persisted entries
        // parses correctly, proving the payloads were consumed.
        assert_eq!(character_values(&items[2]), ["still-aligned"]);
    }

