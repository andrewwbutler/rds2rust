    /// Exercises `skip_object_sequential_value_async`: with lazy_threshold = 2,
    /// the outer list (length 2) is parsed but the inner list (length 4)
    /// exceeds the threshold, so ALL its elements — a PACKAGESXP, a
    /// PERSISTSXP, a BASENAMESPACE_SXP, and a string — are routed through the
    /// skip path. If the skip path fails to consume the string-vec payloads,
    /// the cursor desyncs and the outer list's trailing element misparses.
    #[wasm_bindgen_test]
    async fn test_pseudo_type_payloads_consumed_on_skip_path() {
        let input = MockRdsInput {
            data: SKIP_PATH_STREAM.to_vec(),
        };
        let config = ParseConfig {
            mode: ParseMode::LazyMetadata,
            ..ParseConfig::default()
        }
        .with_lazy_threshold(2);
        let obj = read_rds_async(&input, config, AsyncParseConfig::default())
            .await
            .expect("parse failed")
            .object;

        let items = list_items(&obj);
        assert_eq!(items.len(), 2);
        // The inner list was lazily skipped (represented as an empty list);
        // what matters is that skipping consumed every payload so the element
        // AFTER it is still aligned.
        assert!(
            matches!(unwrap_value(&items[0]), RObject::List(_)),
            "inner element should be a (lazily skipped) list, got {}",
            unwrap_value(&items[0]).variant_name()
        );
        assert_eq!(character_values(&items[1]), ["skip-aligned"]);
    }

    /// The async mirror validates string-vec payloads like the sync consumer:
    /// corrupting the names placeholder in an otherwise valid stream errors.
    #[wasm_bindgen_test]
    async fn test_stringvec_nonzero_placeholder_rejected_sequential() {
        let mut data = PACKAGESXP_STREAM.to_vec();
        // The names placeholder is the 4 bytes after the PACKAGESXP flags
        // word (00 00 00 f8).
        let pos = data
            .windows(4)
            .position(|w| w == [0x00, 0x00, 0x00, 0xf8])
            .expect("PACKAGESXP flags not found")
            + 4;
        data[pos + 3] = 1;
        let input = MockRdsInput { data };
        let config = ParseConfig {
            mode: ParseMode::LazyMetadata,
            ..ParseConfig::default()
        };
        let result = read_rds_async(&input, config, AsyncParseConfig::default()).await;
        assert!(
            result.is_err(),
            "non-zero names placeholder must be rejected by the async path"
        );
    }

